    val faint: Color,
    val onBrand: Color,
    val brand: Color,
    val brandHover: Color,
    val brandSoft: Color,
    val brandBd: Color,
    val brandInk: Color,
    val green: Color,
    val greenSoft: Color,
    val greenInk: Color,
    val greenMid: Color,
    val greenBd: Color,
    val greenTint: Color,
    val orange: Color,
    val orangeSoft: Color,
    val orangeInk: Color,
    val redSoft: Color,
    val redInk: Color,
    val tealSoft: Color,
    val tealBd: Color,
    val teal: Color,
    val figBase: Color,
    val figHighlight: Color,
    val chartTrack: Color,
    val chartArea: Color,
    val toastBg: Color,
    val toastFg: Color,
    val groupColors: Map<String, GroupColorPair>
) {
    fun groupColor(group: String): GroupColorPair =
        groupColors[group] ?: GroupColorPair(subtle, text2)
}

