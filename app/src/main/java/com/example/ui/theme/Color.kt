@Immutable
data class GroupColorPair(val bg: Color, val fg: Color)

@Immutable
data class WorkoutPalette(
    val isDark: Boolean,
    val appBg: Color,
    val surface: Color,
    val subtle: Color,
    val border: Color,
    val borderStrong: Color,
    val text: Color,
    val text2: Color,
